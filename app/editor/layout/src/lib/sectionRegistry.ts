export const getSectionComponent = (
  category: string,
  sectionType: string,
  templateVariant: string,
) => {
  const exactComponent = sectionRegistry[templateVariant];

  if (exactComponent) return exactComponent;
  if (/Page-?\d+$/i.test(templateVariant)) return undefined;

  const componentSectionType =
    sectionType === "MarqueeSlide" ? "Marquee" : sectionType;
  const layoutIndex = Number(templateVariant.match(/(\d+)$/)?.[1] ?? 1);
  const prefix = getCategoryComponentPrefix(category);
  const candidates = [
    getCategorySectionVariant(category, sectionType, templateVariant),
    `${prefix}${componentSectionType}1`,
    `RealEstate${componentSectionType}${layoutIndex}`,
    `RealEstate${componentSectionType}1`,
    `Business${componentSectionType}${layoutIndex}`,
    `Business${componentSectionType}1`,
  ];

  for (const key of candidates) {
    if (sectionRegistry[key]) return sectionRegistry[key];
  }

  const looseMatch = Object.keys(sectionRegistry).find(
    (key) =>
      !/Page\d+$/i.test(key) &&
      key.startsWith(prefix) &&
      new RegExp(`${componentSectionType}\\d+$`, "i").test(key),
  );

  return looseMatch ? sectionRegistry[looseMatch] : undefined;
};
